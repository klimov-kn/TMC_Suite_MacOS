// tmc_cp1251.h — перекодировка строк Windows-версии.
//
// Исходники Windows-версии написаны в CP1251, в этой же кодировке лежат
// подписи внутри файлов задания. На macOS «местная» кодировка — UTF-8, поэтому
// QString::fromLocal8Bit превращает русские строки в мусор: так пропадал текст
// в строке состояния, в окнах сообщений и в надписях поверх сцены FieldView.
//
// Заголовок отдельный, потому что mfc_gdi.h включается и в цели, которые
// собираются без Qt (пересчёт S-матриц), а здесь нужен QString.

#pragma once

#include <QString>

/// CP1251 -> Unicode. len < 0 — строка до нулевого байта.
QString fromCp1251(const char* s, int len = -1);
