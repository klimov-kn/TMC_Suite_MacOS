// gl/gl.h — переходник к системному заголовку OpenGL.
//
// В Windows-версии заголовки OpenGL подключаются как <gl/gl.h> — каталог в
// нижнем регистре (fldviewdoc.h:13, tmcgltext.h:10). В Linux он называется GL,
// а в macOS каталога GL нет вовсе: OpenGL там оформлен рамкой (framework), и
// заголовок зовётся <OpenGL/gl.h>. Править исходники win_src нельзя, поэтому
// здесь стоит переходник.
//
// Почему в ветке Linux #include_next, а не #include <GL/gl.h>: проект
// собирается с диска, смонтированного без учёта регистра, и обычное
// подключение нашло бы этот же файл. #include_next продолжает поиск с
// каталога, следующего за тем, где найден текущий файл, и добирается до
// системного /usr/include/GL/gl.h. В macOS такой опасности нет — имя
// <OpenGL/gl.h> с нашим путём не совпадает, поэтому там обычное подключение.

#pragma once

#ifdef __APPLE__
// Начиная с macOS 10.14 система помечает весь старый OpenGL как устаревший и
// на каждый вызов выдаёт предупреждение. FieldView рисует именно в старом
// стиле (решение Р-3), переписывать его мы не будем, поэтому поток
// предупреждений глушим — иначе он скрывает настоящие ошибки.
#  ifndef GL_SILENCE_DEPRECATION
#    define GL_SILENCE_DEPRECATION 1
#  endif
#  include <OpenGL/gl.h>
#else
#  include_next <GL/gl.h>
#endif
