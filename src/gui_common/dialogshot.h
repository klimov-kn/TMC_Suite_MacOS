// dialogshot.h — снимок диалога без участия человека.
//
// Диалоги перенесены из ресурсов Windows автоматически, поэтому их надо
// проверять глазами: помещаются ли подписи, не обрезаны ли поля, влезает ли
// окно в экран. Делать это вручную по десяткам окон невозможно, поэтому здесь
// средство: построить диалог по номеру ресурса и сохранить его вид в файл.
//
// В поставку не входит — только для проверки при разработке.

#pragma once

#include <QString>

#include "mfc_dialog.h"

namespace tmcshot {

/// Построить диалог по номеру ресурса и сохранить его вид в файл.
/// Возвращает false, если разметки для такого номера нет.
bool grabDialog(UINT idd, const QString &fileName);

/// Снять все диалоги, зарегистрированные программой, в указанный каталог.
/// Возвращает число снятых окон. Имена файлов — по номеру ресурса.
int grabAllDialogs(const QString &directory);

} // namespace tmcshot
