#!/bin/bash
# Быстрая проверка счёта оболочки ядра.
#
# Два важных обстоятельства, выясненных на практике:
#
#  1. Счёт идёт БЫСТРО, когда в задании выключен вывод поля и топологии, и может
#     идти очень долго, когда включён. Для проверки работоспособности этого
#     достаточно: важно, что расчёт идёт, файлы создаются рядом с заданием и
#     результат читается.
#
#  2. Ядро открывает и закрывает выходной файл НА КАЖДОМ ТАКТЕ. Если задание
#     лежит на диске Windows (через /mnt/...), каждая такая операция идёт через
#     границу двух систем, и счёт замедляется в разы. Поэтому и задание, и сам
#     исполняемый файл копируются в рабочий каталог на диске Linux, и счёт идёт
#     там же.
#
# Даже без вывода поля большая модель считается долго — это нормально, а не
# зависание: смотреть надо на строки «После чтения» и «После расчёта».
#
#   [BUILD=build-compat] tools/dev/check_kernel.sh planarrt_h|planarrt_x [минуты]
set -u
cd "$(dirname "$0")/../.."
BUILD="${BUILD:-build}"
APP="${1:-planarrt_h}"
LIMIT_MIN="${2:-10}"

WORK=/tmp/tmc_kernel_$APP
rm -rf "$WORK" && mkdir -p "$WORK"
cp samples/$APP/* "$WORK"/ 2>/dev/null

# Ядро кладём рядом с заданием: так весь обмен идёт по диску Linux.
cp "$BUILD/bin/${APP}_runcheck" "$WORK"/ 2>/dev/null || {
    echo "нет средства проверки $BUILD/bin/${APP}_runcheck"; exit 1; }

TPL=$(ls "$WORK"/*.tpl 2>/dev/null | grep -iv test | head -1)
[ -n "$TPL" ] || { echo "нет файла задания в samples/$APP"; exit 1; }

# Вывод поля делает счёт долгим — для проверки его убираем.
FAST="$WORK/fast.tpl"
grep -v FIELD_DISTRIBUTION "$TPL" > "$FAST"
echo "задание: $(basename "$TPL") без вывода поля -> fast.tpl"
echo "рабочий каталог: $WORK (диск Linux)"

cd "$WORK"
START=$(date +%s)
# Вывод небуферизованный: иначе при остановке по времени не видно даже того,
# что уже посчиталось.
stdbuf -o0 timeout $((LIMIT_MIN * 60)) "./${APP}_runcheck" fast.tpl 2>&1 | tail -8
CODE=$?
echo "время счёта: $(( $(date +%s) - START )) c (код $CODE)"

echo "файлы, созданные счётом:"
find . -newer fast.tpl -type f -printf "  %f  %s байт\n" 2>/dev/null | head -8
BAD=$(ls | grep -F '' | head -3)
[ -z "$BAD" ] && echo "имён с обратным слэшем нет" || echo "ОСТАЛИСЬ имена с обратным слэшем: $BAD"
